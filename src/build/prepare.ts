import path from "node:path";

import { readUtf8, writeUtf8IfChanged } from "../core/files.js";
import { PatchError } from "../core/text-edit.js";
import type { Upstream } from "../upstreams.js";

export type BuildVariant = "armAll" | "arm64" | "x86_64" | "universal";

const variantAbis: Record<BuildVariant, readonly string[]> = {
  armAll: ["armeabi-v7a", "arm64-v8a"],
  arm64: ["arm64-v8a"],
  x86_64: ["x86_64"],
  universal: ["armeabi-v7a", "arm64-v8a", "x86", "x86_64"],
};

function gradleOverride(abis: readonly string[], kotlinDsl: boolean, includeSplits: boolean): string {
  const values = abis.map((abi) => `'${abi}'`).join(", ");
  if (kotlinDsl) {
    const kotlinValues = abis.map((abi) => `"${abi}"`).join(", ");
    const splits = includeSplits ? `
    splits {
        abi {
            isEnable = false
        }
    }` : "";
    return `

// CROSSGRAM ABI OVERRIDE BEGIN - generated by crossgram-android-patcher
android {
    defaultConfig {
        ndk {
            abiFilters.clear()
            abiFilters.addAll(setOf(${kotlinValues}))
        }
    }
    productFlavors.configureEach {
        ndk {
            abiFilters.clear()
            abiFilters.addAll(setOf(${kotlinValues}))
        }
    }
${splits}
}
// CROSSGRAM ABI OVERRIDE END
`;
  }
  const splits = includeSplits ? `
    splits {
        abi {
            enable false
        }
    }` : "";
  return `

// CROSSGRAM ABI OVERRIDE BEGIN - generated by crossgram-android-patcher
android {
    defaultConfig {
        ndk {
            abiFilters.clear()
            abiFilters.addAll([${values}])
        }
    }
    productFlavors.configureEach {
        ndk {
            abiFilters.clear()
            abiFilters.addAll([${values}])
        }
    }
${splits}
}
// CROSSGRAM ABI OVERRIDE END
`;
}

function updateGradleOverride(
  source: string,
  abis: readonly string[],
  kotlinDsl: boolean,
  includeSplits: boolean,
): string {
  const block = gradleOverride(abis, kotlinDsl, includeSplits).trim();
  const current = /\/\/ CROSSGRAM ABI OVERRIDE BEGIN[^\r\n]*[\s\S]*?\/\/ CROSSGRAM ABI OVERRIDE END/;
  if (current.test(source)) return source.replace(current, block);

  // Compatibility with the first development version, whose generated block
  // was always appended at EOF and did not have an END marker.
  const legacy = /\n*\/\/ CROSSGRAM ABI OVERRIDE - generated by crossgram-android-patcher[\s\S]*$/;
  if (legacy.test(source)) return `${source.replace(legacy, "").trimEnd()}\n\n${block}\n`;
  return `${source.trimEnd()}\n\n${block}\n`;
}

export async function prepareBuild(root: string, upstream: Upstream, variant: BuildVariant): Promise<string[]> {
  const abis = variantAbis[variant];
  if (!abis) throw new Error(`Unknown build variant: ${variant}`);
  const candidates = [upstream.id === "nnngram" || upstream.id === "nullgram"
    ? "TMessagesProj/build.gradle.kts"
    : "TMessagesProj/build.gradle"];
  if (upstream.id === "telegram") candidates.push("TMessagesProj_App/build.gradle");
  const changed: string[] = [];
  for (const relative of candidates) {
    const file = path.join(root, relative);
    const source = await readUtf8(file);
    if (!/\bandroid\s*\{/.test(source)) {
      throw new PatchError(relative, "could not find the Android Gradle DSL");
    }
    const includeSplits = upstream.id !== "telegram" || relative.startsWith("TMessagesProj_App/");
    const updated = updateGradleOverride(source, abis, relative.endsWith(".kts"), includeSplits);
    if (await writeUtf8IfChanged(file, updated)) changed.push(relative);
  }
  if (upstream.id === "telegram") {
    const relative = "gradle/wrapper/gradle-wrapper.properties";
    const file = path.join(root, relative);
    const source = await readUtf8(file);
    const target = "distributionUrl=https\\://services.gradle.org/distributions/gradle-8.7-bin.zip";
    let updated = source;
    if (!source.includes(target)) {
      const pattern = /^distributionUrl=.*gradle-[\d.]+-(?:all|bin)\.zip\s*$/gm;
      const matches = [...source.matchAll(pattern)];
      if (matches.length !== 1) {
        throw new PatchError(relative, `expected one Gradle wrapper distribution, found ${matches.length}`);
      }
      updated = source.replace(new RegExp(pattern.source, "m"), target);
    }
    if (await writeUtf8IfChanged(file, updated)) changed.push(relative);
  }
  if (upstream.id === "nullgram") {
    const jniRelative = "TMessagesProj/jni/jni.c";
    const jniFile = path.join(root, jniRelative);
    const jniSource = await readUtf8(jniFile);
    const marker = "/* CROSSGRAM: accept the Crossgram release certificate. */";
    let jniUpdated = jniSource;
    if (!jniUpdated.includes(marker)) {
      const check = /[ \t]*if \(!checkSignature\(verify_signature\(vm\)\)\) \{\r?\n[ \t]*return JNI_ERR;\r?\n[ \t]*\}/;
      const matches = [...jniUpdated.matchAll(new RegExp(check.source, "g"))];
      if (matches.length !== 1) {
        throw new PatchError(jniRelative, `expected one upstream signature gate, found ${matches.length}`);
      }
      jniUpdated = jniUpdated.replace(check, `\n    ${marker}`);
    }
    if (await writeUtf8IfChanged(jniFile, jniUpdated)) changed.push(jniRelative);
  }
  if (upstream.id === "nagram") {
    for (const relative of [
      "TMessagesProj/jni/build_boringssl.sh",
      "TMessagesProj/jni/build_libvpx_clang.sh",
      "TMessagesProj/jni/build_ffmpeg_clang.sh",
    ]) {
      const file = path.join(root, relative);
      const source = await readUtf8(file);
      let updated = source;
      if (!updated.includes("CROSSGRAM_NATIVE_TARGETS")) {
        const matches = [...updated.matchAll(/^([ \t]*)build\s+(?:arm64\s+arm|arm\s+arm64)[ \t]*$/gm)];
        if (matches.length !== 1) {
          throw new PatchError(relative, `expected one native target list, found ${matches.length}`);
        }
        updated = updated.replace(
          /^([ \t]*)build\s+(?:arm64\s+arm|arm\s+arm64)[ \t]*$/m,
          "$1build ${CROSSGRAM_NATIVE_TARGETS:-arm64 arm}",
        );
      }

      if (relative.endsWith("build_libvpx_clang.sh")) {
        const flags = [
          {
            before: 'OPTIMIZE_CFLAGS="-O3 -march=x86-64 -mtune=intel -msse4.2 -mpopcnt -m64 -fPIC"',
            after: 'OPTIMIZE_CFLAGS="-O3" # CROSSGRAM NDK-compatible x86_64 flags',
          },
          {
            before: 'OPTIMIZE_CFLAGS="-O3 -march=i686 -mtune=intel -msse3 -mfpmath=sse -m32 -fPIC"',
            after: 'OPTIMIZE_CFLAGS="-O3" # CROSSGRAM NDK-compatible x86 flags',
          },
        ];
        for (const { before, after } of flags) {
          if (updated.includes(after)) continue;
          const count = updated.split(before).length - 1;
          if (count !== 1) {
            throw new PatchError(relative, `expected one legacy x86 compiler flag set, found ${count}`);
          }
          updated = updated.replace(before, after);
        }
      }
      if (await writeUtf8IfChanged(file, updated)) changed.push(relative);
    }

    const headerRelative = "TMessagesProj/jni/patch_ffmpeg.sh";
    const headerFile = path.join(root, headerRelative);
    const headerSource = await readUtf8(headerFile);
    let headerUpdated = headerSource;
    const headerMarker = "# CROSSGRAM x86 FFmpeg internal headers enabled";
    if (!headerUpdated.includes(headerMarker)) {
      const commented = /^#cp (ffmpeg\/[^\r\n]+ ffmpeg\/build\/(?:x86|x86_64)\/include\/[^\r\n]+)$/gm;
      const matches = [...headerUpdated.matchAll(commented)];
      const hasIsomCopies = ["x86", "x86_64"].every((abi) =>
        matches.some((match) => match[1]?.endsWith(`ffmpeg/build/${abi}/include/libavformat/isom.h`)),
      );
      if (!hasIsomCopies) {
        throw new PatchError(headerRelative, "could not find disabled x86 FFmpeg isom.h copies");
      }
      headerUpdated = `${headerUpdated.replace(commented, "cp $1").trimEnd()}\n\n${headerMarker}\n`;
    }
    if (await writeUtf8IfChanged(headerFile, headerUpdated)) changed.push(headerRelative);
  }
  return changed;
}

export function getVariantAbis(variant: BuildVariant): readonly string[] {
  const result = variantAbis[variant];
  if (!result) throw new Error(`Unknown build variant: ${variant}`);
  return result;
}
