export const rustLogFallback = `// Generated by crossgram-android-patcher for ABIs without the upstream Rust archive.
#include <android/log.h>
#include <cstdint>

namespace {
uint8_t writeLog(int priority, const char *tag, const char *message) {
    return static_cast<uint8_t>(__android_log_write(priority, tag, message) >= 0);
}
}

extern "C" uint8_t logd(const char *tag, const char *message) {
    return writeLog(ANDROID_LOG_DEBUG, tag, message);
}

extern "C" uint8_t logi(const char *tag, const char *message) {
    return writeLog(ANDROID_LOG_INFO, tag, message);
}

extern "C" uint8_t logw(const char *tag, const char *message) {
    return writeLog(ANDROID_LOG_WARN, tag, message);
}

extern "C" uint8_t loge(const char *tag, const char *message) {
    return writeLog(ANDROID_LOG_ERROR, tag, message);
}
`;
